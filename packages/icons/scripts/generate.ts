/**
 * Builds `src/generated/icons.ts` (icon nodes) and `src/generated/svg.ts` (SVG strings)
 * from the shapes in `@0xdolan/deq-core`, rendered with default options.
 *
 *   node scripts/generate.ts           write the files
 *   node scripts/generate.ts --check   fail if a file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { listShapes, render } from "@0xdolan/deq-core";

import { iconExportName } from "../src/names.ts";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "src", "generated");
const HEADER = [
  "// Generated by scripts/generate.ts from @0xdolan/deq-core.",
  "// Do not edit: run `pnpm --filter @0xdolan/deq-icons generate`.",
];
const TAGS = new Set(["circle", "ellipse", "line", "path", "polygon", "polyline"]);
const RESERVED = new Set(["default", "icons", "toSvg", "rootAttributes", "nodeMarkup"]);

type Element = [string, Record<string, string>];

/** Parse core's flat child markup (`<tag a="b"/>` elements, no nesting) into elements. */
export function parseNode(id: string, inner: string): Element[] {
  const out: Element[] = [];
  let i = 0;
  while (i < inner.length) {
    const end = inner.indexOf("/>", i);
    const space = inner.indexOf(" ", i);
    if (inner[i] !== "<" || end === -1 || space === -1 || space > end)
      throw new Error(`${id}: unexpected markup at ${String(i)}`);
    const tag = inner.slice(i + 1, space);
    if (!TAGS.has(tag)) throw new Error(`${id}: unexpected <${tag}>`);
    const attrs: Record<string, string> = {};
    let j = space;
    while (j < end) {
      const eq = inner.indexOf('="', j);
      const close = inner.indexOf('"', eq + 2);
      if (eq === -1 || eq > end) break;
      attrs[inner.slice(j, eq).trim()] = inner.slice(eq + 2, close);
      j = close + 1;
    }
    if (Object.values(attrs).some((v) => /[&<>"']/.test(v)))
      throw new Error(`${id}: escaped attribute values are not expected`);
    out.push([tag, attrs]);
    i = end + 2;
  }
  return out;
}

/** The child markup of a core SVG document (everything after the root and title). */
export function innerMarkup(svg: string): string {
  const open = svg.indexOf(">");
  const titleEnd = svg.indexOf("</title>");
  const start = titleEnd === -1 ? open + 1 : titleEnd + "</title>".length;
  if (!svg.endsWith("</svg>")) throw new Error("not an SVG document");
  return svg.slice(start, -"</svg>".length);
}

export function generate(): { icons: string; svg: string } {
  const icons = [...HEADER, 'import type { DeqIcon } from "../types.js";', ""];
  const svg = [...HEADER, ""];
  const map: string[] = [];
  const seen = new Set<string>();
  for (const shape of listShapes()) {
    const name = iconExportName(shape.id);
    if (RESERVED.has(name) || seen.has(name)) throw new Error(`export name clash: ${name}`);
    seen.add(name);
    const doc = render(shape.id);
    const node = parseNode(shape.id, innerMarkup(doc));
    icons.push(
      `/** ${shape.names.en} (\`${shape.id}\`). */`,
      `export const ${name}: DeqIcon = ${JSON.stringify({ name: shape.id, title: shape.names.en, node })};`,
    );
    svg.push(
      `/** ${shape.names.en} (\`${shape.id}\`). */`,
      `export const ${name} = ${JSON.stringify(doc)};`,
    );
    map.push(`  ${JSON.stringify(shape.id)}: ${name},`);
  }
  icons.push(
    "",
    "/** Every icon by catalog id. Importing this keeps all icons in a bundle. */",
    "export const icons: Readonly<Record<string, DeqIcon>> = {",
    ...map,
    "};",
    "",
  );
  svg.push("");
  return { icons: icons.join("\n"), svg: svg.join("\n") };
}

function main(): void {
  const files = generate();
  const targets: [string, string][] = [
    [join(OUT, "icons.ts"), files.icons],
    [join(OUT, "svg.ts"), files.svg],
  ];
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, text] of targets) {
    if (!check) writeFileSync(file, text);
    else if (readFileSync(file, "utf8") !== text) {
      console.error(`${file} is out of date: run \`pnpm --filter @0xdolan/deq-icons generate\``);
      stale = true;
    }
  }
  if (stale) process.exit(1);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
