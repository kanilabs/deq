/**
 * Builds `src/generated/shapes.ts` and `src/generated/flag.ts` from `spec/catalog.json`,
 * `spec/shapes/*.json` and `spec/flag.json`, plus the same data as JSON for the Python and
 * Rust ports (`deq_shapes/data/shapes.json`, `rust/deq-shapes/data/shapes.json`).
 *
 *   node scripts/generate-shapes.ts           write the files
 *   node scripts/generate-shapes.ts --check   fail if any file is out of date
 */
import {
  closeSync,
  constants,
  fstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { FlagData, FlagVariant } from "../src/flag.ts";
import type { ShapeData } from "../src/types.ts";

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC_DIR = join(here, "..", "..", "..", "spec");
export const OUT_FILE = join(here, "..", "src", "generated", "shapes.ts");
export const FLAG_FILE = join(here, "..", "src", "generated", "flag.ts");
const ROOT = join(here, "..", "..", "..");
/** The JSON copies read by the Python and Rust ports. */
export const PORT_FILES = [
  join(ROOT, "python", "deq-shapes", "src", "deq_shapes", "data", "shapes.json"),
  join(ROOT, "rust", "deq-shapes", "data", "shapes.json"),
];

/** Largest spec file accepted (bytes), the same limit as `deq-spec`. */
const MAX_FILE_BYTES = 256 * 1024;
const ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

interface Catalog {
  readonly categories: readonly { readonly shapes: readonly unknown[] }[];
}

/** A spec shape file: everything in {@link ShapeData} plus documentation fields. */
type SpecShape = ShapeData & Record<string, unknown>;

/** `O_NOFOLLOW` where the platform has it (not on Windows). */
const NOFOLLOW: number = (constants as Partial<typeof constants>).O_NOFOLLOW ?? 0;

/**
 * Read a regular file as UTF-8, refusing symlinks and files over `maxBytes`. The file is
 * opened once and checked through its descriptor, so it cannot be swapped between the
 * check and the read.
 */
export function readText(path: string, maxBytes: number = MAX_FILE_BYTES): string {
  let fd: number;
  try {
    fd = openSync(path, constants.O_RDONLY | NOFOLLOW);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ELOOP")
      throw new Error(`${path}: refusing symlink`, { cause: err });
    throw err;
  }
  try {
    const st = fstatSync(fd);
    if (!st.isFile()) throw new Error(`${path}: not a regular file`);
    if (st.size > maxBytes) throw new Error(`${path}: larger than ${String(maxBytes)} bytes`);
    return readFileSync(fd, "utf8");
  } finally {
    closeSync(fd);
  }
}

/** Read a JSON file, refusing symlinks and oversized files. */
export function readJson(path: string): unknown {
  return JSON.parse(readText(path));
}

/** The render-relevant fields of one spec shape, in a fixed key order. */
function pick(s: SpecShape): ShapeData {
  return {
    id: s.id,
    version: s.version,
    category: s.category,
    names: {
      en: s.names.en,
      ckb: { text: s.names.ckb.text, status: s.names.ckb.status },
      kmr: { text: s.names.kmr.text, status: s.names.kmr.status },
    },
    aliases: s.aliases,
    tags: s.tags,
    layers: s.layers,
    symmetry: s.symmetry,
    parameters: s.parameters,
    primitives: s.primitives,
  };
}

/** Every catalog shape, in catalog order, with only the render-relevant fields. */
export function loadShapes(specDir: string = SPEC_DIR): ShapeData[] {
  const catalog = readJson(join(specDir, "catalog.json")) as Catalog;
  const shapes: ShapeData[] = [];
  const seen = new Set<string>();
  for (const category of catalog.categories) {
    for (const id of category.shapes) {
      if (typeof id !== "string" || !ID.test(id))
        throw new Error(`bad shape id ${JSON.stringify(id)}`);
      if (seen.has(id)) throw new Error(`duplicate shape id ${id}`);
      seen.add(id);
      const shape = readJson(join(specDir, "shapes", `${id}.json`)) as SpecShape;
      if (shape.id !== id)
        throw new Error(`spec/shapes/${id}.json has id ${JSON.stringify(shape.id)}`);
      shapes.push(pick(shape));
    }
  }
  return shapes;
}

/** The generated shapes module's source text. */
export function generateShapes(specDir: string = SPEC_DIR): string {
  return [
    "// Generated by scripts/generate-shapes.ts from spec/catalog.json and spec/shapes/.",
    "// Do not edit: run `pnpm --filter @0xdolan/deq-core generate`.",
    'import type { ShapeData } from "../types.js";',
    "",
    "/** Every catalog shape, in catalog order. */",
    "export const SHAPES: readonly ShapeData[] = [",
    ...loadShapes(specDir).map((s) => `  ${JSON.stringify(s)},`),
    "];",
    "",
  ].join("\n");
}

interface SpecFlag {
  readonly names: { readonly en: string };
  readonly viewBox: [number, number];
  readonly colors: readonly { readonly id: string; readonly hex: string }[];
  readonly bands: readonly {
    readonly color: string;
    readonly y: number;
    readonly height: number;
  }[];
  readonly sun: {
    readonly color: string;
    readonly rays: number;
    readonly rotation: number;
    readonly center: [number, number];
    readonly outerRadius: number;
    readonly innerRadius: number;
  };
  readonly variants: readonly {
    readonly id: string;
    readonly description: string;
    readonly aspectRatio: string;
    readonly paint: {
      readonly field?: string;
      readonly bands?: string;
      readonly dividers?: string;
      readonly frame?: string;
      readonly sun?: string;
      readonly sunOutline?: string;
      readonly strokeToHeight?: number;
    };
  }[];
}

/** The flag data with paint names resolved to colours and crops computed. */
export function loadFlag(specDir: string = SPEC_DIR): FlagData {
  const spec = readJson(join(specDir, "flag.json")) as SpecFlag;
  const hex = new Map(spec.colors.map((c) => [c.id, c.hex]));
  const color = (name: string | undefined): string | null => {
    if (name === undefined || name === "none") return null;
    if (name === "black") return "#000000";
    if (name === "currentColor") return name;
    const c = hex.get(name);
    if (c === undefined) throw new Error(`flag: unknown colour ${name}`);
    return c;
  };
  const [vw, vh] = spec.viewBox;
  const variants = spec.variants.map((x): FlagVariant => {
    const [rw, rh] = x.aspectRatio.split(":").map(Number);
    if (!rw || !rh) throw new Error(`flag: bad aspect ratio ${x.aspectRatio}`);
    const w = Math.min(vw, (vh * rw) / rh);
    const bands = x.paint.bands ?? "none";
    if (bands !== "none" && bands !== "flag-colors") throw new Error(`flag: bad bands ${bands}`);
    const ratio = x.paint.strokeToHeight ?? 0;
    return {
      id: x.id,
      description: x.description,
      crop: [(vw - w) / 2, w],
      field: color(x.paint.field),
      bands: bands === "flag-colors",
      dividers: color(x.paint.dividers),
      frame: color(x.paint.frame),
      sun: color(x.paint.sun),
      sunOutline: color(x.paint.sunOutline),
      strokeWidth: ratio * vh,
    };
  });
  const { rays, rotation, center, outerRadius, innerRadius } = spec.sun;
  return {
    name: spec.names.en,
    viewBox: [vw, vh],
    bands: spec.bands.map((b) => ({ y: b.y, height: b.height, color: color(b.color) ?? "none" })),
    sun: { rays, rotation, center, outerRadius, innerRadius },
    variants,
  };
}

/** The generated flag module's source text. */
export function generateFlag(specDir: string = SPEC_DIR): string {
  return [
    "// Generated by scripts/generate-shapes.ts from spec/flag.json.",
    "// Do not edit: run `pnpm --filter @0xdolan/deq-core generate`.",
    'import type { FlagData } from "../flag.js";',
    "",
    "/** The render-relevant part of spec/flag.json, paint resolved to colours. */",
    `export const FLAG: FlagData = ${JSON.stringify(loadFlag(specDir), null, 2)};`,
    "",
  ].join("\n");
}

/** The JSON data file of the Python and Rust ports (one shape per line). */
export function generatePortData(specDir: string = SPEC_DIR): string {
  const shapes = loadShapes(specDir).map((s) => `    ${JSON.stringify(s)}`);
  return [
    "{",
    '  "$comment": "Generated by packages/core/scripts/generate-shapes.ts from spec/; do not edit. Run `pnpm --filter @0xdolan/deq-core generate`.",',
    `  "flag": ${JSON.stringify(loadFlag(specDir))},`,
    '  "shapes": [',
    shapes.join(",\n"),
    "  ]",
    "}",
    "",
  ].join("\n");
}

/** Every generated file and its expected text. */
export function generatedFiles(specDir: string = SPEC_DIR): [string, string][] {
  const data = generatePortData(specDir);
  return [
    [OUT_FILE, generateShapes(specDir)],
    [FLAG_FILE, generateFlag(specDir)],
    ...PORT_FILES.map((f): [string, string] => [f, data]),
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  for (const [file, text] of generatedFiles()) {
    if (check) {
      if (readText(file, 4 * 1024 * 1024) !== text) {
        console.error(`${file} is out of date: run \`pnpm --filter @0xdolan/deq-core generate\``);
        process.exit(1);
      }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
}
