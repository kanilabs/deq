import { render } from "@0xdolan/deq-core";
import { compileScript, compileTemplate, parse } from "@vue/compiler-sfc";
import { compile } from "svelte/compiler";
import ts from "typescript";
import { runInNewContext } from "node:vm";
import { describe, expect, it } from "vitest";

import { componentName, toReact, toSvelte, toVue } from "./components.js";
import { resolveItem } from "./input.js";

interface El {
  readonly tag: string;
  readonly props: Record<string, unknown>;
  readonly children: El[];
}

/** Transpile a generated React component and call it with a tiny `h` that builds a tree. */
function runReact(source: string, props: Record<string, unknown> = {}): El {
  const out = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: {
      jsx: ts.JsxEmit.React,
      jsxFactory: "h",
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  });
  expect(out.diagnostics ?? []).toEqual([]);
  const h = (tag: string, p: Record<string, unknown> | null, ...kids: unknown[]): El => ({
    tag,
    props: p ?? {},
    children: kids.flat().filter((k): k is El => typeof k === "object" && k !== null),
  });
  const exports: Record<string, unknown> = {};
  // Test-only evaluation of the trusted generated component, in its own context.
  runInNewContext(out.outputText, { exports, h, require: () => ({}) });
  const component = exports["default"] as (p: Record<string, unknown>) => El;
  return component(props);
}

const tags = (el: El): string[] => [el.tag, ...el.children.flatMap(tags)];

describe("componentName", () => {
  it("PascalCases and prefixes names that do not start with a letter", () => {
    expect(componentName("roj-half-sun")).toBe("RojHalfSun");
    expect(componentName("7-dots")).toBe("Deq7Dots");
    expect(componentName("a--b")).toBe("AB");
  });
});

describe("React", () => {
  const r = resolveItem({
    shape: "roj-half-sun",
    options: { size: 32, strokeWidth: 1.5, color: "#c00" },
  });

  it("TSX is valid TypeScript with a typed props interface", () => {
    const tsx = toReact(r, true);
    expect(tsx).toContain("export interface RojHalfSunProps extends SVGProps<SVGSVGElement>");
    expect(tsx.startsWith("// Generated by @0xdolan/deq-exporters.")).toBe(true);
    const el = runReact(tsx);
    expect(el.tag).toBe("svg");
    expect(el.props).toMatchObject({
      width: 32,
      height: 32,
      color: "#c00",
      strokeWidth: 1.5,
      role: "img",
      "aria-label": "Half sun",
      viewBox: "0 0 24 24",
      strokeLinecap: "round",
    });
  });

  it("JSX renders the same elements as core", () => {
    const el = runReact(toReact(r, false));
    const core = render("roj-half-sun", { size: 32 });
    const coreTags = [...core.matchAll(/<([a-z]+)[\s>/]/g)].map((m) => m[1]);
    expect(tags(el)).toEqual(coreTags);
  });

  it("props override the defaults; an empty title marks it decorative", () => {
    const el = runReact(toReact(r, false), { size: 16, title: "", className: "x" });
    expect(el.props).toMatchObject({ width: 16, "aria-hidden": true, className: "x" });
    expect(el.props["role"]).toBeUndefined();
    expect(tags(el)).not.toContain("title");
  });

  it("escapes string defaults for script contexts", () => {
    const tsx = toReact(
      resolveItem({ shape: "chevron", options: { title: "</script><x>" } }),
      true,
    );
    expect(tsx).toContain('title = "\\u003c/script\\u003e\\u003cx\\u003e"');
    expect(runReact(tsx).props["aria-label"]).toBe("</script><x>");
  });
});

describe("Vue", () => {
  it("compiles as a single-file component", () => {
    const source = toVue(
      resolveItem({ shape: "roj-half-sun", options: { layerColors: { rays: "red" } } }),
    );
    const { descriptor, errors } = parse(source, { filename: "RojHalfSun.vue" });
    expect(errors).toEqual([]);
    const script = compileScript(descriptor, { id: "x" });
    expect(script.content).toMatch(/size: \{[^}]*default: 24/);
    const template = compileTemplate({
      source: descriptor.template?.content ?? "",
      filename: "RojHalfSun.vue",
      id: "x",
      compilerOptions: { bindingMetadata: script.bindings ?? {} },
    });
    expect(template.errors).toEqual([]);
    expect(template.code).toContain("data-layer");
  });
});

describe("Svelte", () => {
  it("compiles as a Svelte 5 component", () => {
    const source = toSvelte(resolveItem({ shape: "roj-half-sun", options: { title: "{evil}" } }));
    expect(source).toContain('title = "{evil}"');
    const out = compile(source, { filename: "RojHalfSun.svelte", generate: "server" });
    expect(out.js.code).toContain("$$props");
    const client = compile(source, { filename: "RojHalfSun.svelte", generate: "client" });
    expect(client.warnings.map((w) => w.code)).toEqual([]);
  });
});
