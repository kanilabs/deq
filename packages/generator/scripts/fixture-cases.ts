/**
 * The golden Leet and pattern fixtures in `spec/fixtures/leet/` (ADR 0015). The Python and
 * Rust ports must write every file byte for byte and decode every `decoded` case.
 */
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type * as Generator from "../src/index.ts";
import type { LeetOptions, PatternOptions } from "../src/index.ts";

export interface LeetCase {
  /** Unique, file-safe name. */
  readonly name: string;
  readonly leet?: { readonly text: string; readonly options: LeetOptions };
  readonly pattern?: PatternOptions;
  /** For `basic` cases: the text `decodeLeet` reads back. */
  readonly decoded?: string;
  /** Path of the expected SVG, relative to `spec/fixtures/leet/`. */
  readonly file: string;
}

/** Where the fixtures live. */
export const LEET_FIXTURES = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
  "spec",
  "fixtures",
  "leet",
);

type Lib = Pick<typeof Generator, "leet" | "pattern" | "leetTable">;

/** Every table character, in lines of at most `width`. */
function allChars(lib: Lib, script: "latin" | "sorani", width: number): string {
  const chars = lib.leetTable(script).glyphs.map((e) => e.char);
  const lines: string[] = [];
  for (let i = 0; i < chars.length; i += width) lines.push(chars.slice(i, i + width).join(""));
  return lines.join("\n");
}

/** The fixture cases, built with `lib` (the source in tests, `dist/` in the script). */
export function leetCases(lib: Lib): LeetCase[] {
  const cases: LeetCase[] = [];
  const add = (name: string, text: string, options: LeetOptions = {}): void => {
    const level = options.level ?? "basic";
    const r = lib.leet(text, options);
    cases.push({
      name,
      leet: { text, options },
      ...(level === "basic" ? { decoded: r.text } : {}),
      file: `${name}.svg`,
    });
  };
  for (const script of ["latin", "sorani"] as const) {
    const text = allChars(lib, script, 10);
    add(`${script}-basic`, text, { script });
    add(`${script}-advanced`, text, { script, level: "advanced", seed: 42 });
    add(`${script}-full`, text, { script, level: "full" });
  }
  add("latin-sentence", "Deq: the old tattoos of Kurdistan, 1920 - 2026!", { level: "advanced" });
  add("latin-seed-0", "Kurdistan", { level: "advanced", seed: 0 });
  add("latin-seed-max", "Kurdistan", { level: "advanced", seed: 4294967295 });
  add("latin-mixed-input", "  dêq\u200D — Şêx Ûsiv ☃\r\n\r\nçi?  ");
  add("sorani-sentence", "دەق، نەخشی کۆنی کوردستان", { align: "center" });
  add("sorani-input", "كـوردستان ۲۰۲٦ ?");
  add("layout", "Deq\nLeet\nKurd", {
    letterSpacing: 0,
    lineSpacing: 12,
    align: "end",
    size: 48,
    padding: 2,
    background: "#FFFFFF",
  });
  add("render-options", "Roj 9", {
    color: "#ED2024",
    strokeWidth: 1.5,
    absoluteStrokeWidth: true,
    fill: "#FEBD11",
    fillOpacity: 0.5,
    strokeOpacity: 0.8,
    linecap: "square",
    linejoin: "bevel",
    dotScale: 1.5,
    title: "Roj",
    ariaLabel: "Roj nine",
  });
  add("colors", "KURDISTAN", { colors: ["#ED2024", "#FFFFFF", "#278E43"], background: "#000" });
  add("no-title", "DEQ", { title: "" });
  for (const kind of ["band", "grid", "rosette", "border"] as const) {
    for (const seed of [1, 42]) {
      const name = `pattern-${kind}-${String(seed)}`;
      cases.push({ name, pattern: { kind, seed }, file: `${name}.svg` });
    }
  }
  const extra: [string, PatternOptions][] = [
    ["pattern-band-motifs", { motifs: ["chevron", "dot", "ring"], count: 11, seed: 5 }],
    [
      "pattern-grid-spaced",
      { kind: "grid", cols: 4, rows: 2, spacing: 8, colors: ["#ED2024", "#278E43"] },
    ],
    ["pattern-rosette-12", { kind: "rosette", petals: 12, spacing: 0, seed: 9 }],
    ["pattern-border-wide", { kind: "border", cols: 9, rows: 4, seed: 3, size: 16 }],
  ];
  for (const [name, pattern] of extra) cases.push({ name, pattern, file: `${name}.svg` });
  return cases;
}

/** The SVG of one case. */
export function renderLeetCase(c: LeetCase, lib: Lib): string {
  if (c.leet) return lib.leet(c.leet.text, c.leet.options).svg;
  return lib.pattern(c.pattern).svg;
}

/** The manifest file's text. */
export function leetManifest(cases: readonly LeetCase[]): string {
  const body = {
    $comment:
      "Generated by packages/generator/scripts/fixtures.ts; do not edit. Each case renders to the SVG in `file` byte for byte, and every `decoded` case decodes to that text (ADR 0015).",
    version: 1,
    cases,
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

/** Every fixture file (relative to `spec/fixtures/leet/`) and its text. */
export function leetFiles(lib: Lib): Map<string, string> {
  const cases = leetCases(lib);
  const files = new Map([["manifest.json", leetManifest(cases)]]);
  for (const c of cases) files.set(c.file, renderLeetCase(c, lib));
  return files;
}
