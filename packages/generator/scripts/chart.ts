/**
 * Writes `docs/design/leet-chart.svg`, the visual chart of the Deq Leet tables: for each
 * character its basic glyph, up to two advanced alternatives, the full-level motif, the
 * shapes it uses and how well it reads (ADR 0015).
 *
 *   node scripts/chart.ts           write the chart
 *   node scripts/chart.ts --check   fail if the chart is out of date
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type * as Generator from "../src/index.ts";
import type { Glyph, LeetEntry } from "../src/index.ts";
import { readText } from "./generate-leet.ts";

export const CHART_FILE = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
  "docs",
  "design",
  "leet-chart.svg",
);

type Lib = Pick<typeof Generator, "leetTable" | "sceneSvg">;

const FIT: Readonly<Record<LeetEntry["fit"], string>> = {
  good: "#1b7f3b",
  fair: "#b26a00",
  rough: "#c0392b",
  count: "#2f5fb3",
};
const COLS = 6;
const CW = 172;
const CH = 116;
const M = 24;
const G = 56;

const esc = (s: string): string =>
  s.replace(/&/gu, "&amp;").replace(/</gu, "&lt;").replace(/>/gu, "&gt;");

/** The chart's SVG text. */
export function leetChart(lib: Lib): string {
  const glyph = (g: Glyph, x: number, y: number, size: number): string =>
    lib
      .sceneSvg({ width: 24, height: 24, cells: [{ x: 0, y: 0, glyph: g }] }, { title: "" })
      .replace(
        / width="24" height="24"/u,
        ` x="${String(x)}" y="${String(y)}" width="${String(size)}" height="${String(size)}"`,
      );
  let y = 84;
  let body = "";
  for (const script of ["latin", "sorani"] as const) {
    const table = lib.leetTable(script);
    const heading =
      script === "latin" ? "Latin, Kurmanji, digits and punctuation (LTR)" : "Sorani (RTL)";
    body += `<text x="${String(M)}" y="${String(y)}" font-size="18" font-weight="700">${heading}</text>`;
    y += 16;
    const font =
      script === "sorani" ? ' font-family="Noto Naskh Arabic, Vazirmatn, sans-serif"' : "";
    table.glyphs.forEach((e, i) => {
      const cx = M + (i % COLS) * CW;
      const cy = y + Math.floor(i / COLS) * CH;
      body += `<rect x="${String(cx)}" y="${String(cy)}" width="${String(CW - 8)}" height="${String(CH - 8)}" rx="8" fill="#fff" stroke="#ddd"/>`;
      body += `<text x="${String(cx + 10)}" y="${String(cy + 30)}" font-size="26" font-weight="600" fill="#111"${font}>${esc(e.char)}</text>`;
      body += `<rect x="${String(cx + 44)}" y="${String(cy + 8)}" width="${String(G)}" height="${String(G)}" fill="#f6f6f6"/>`;
      body += glyph(e.basic, cx + 44, cy + 8, G);
      [...e.advanced.slice(0, 2), e.full].forEach((g, j) => {
        body += glyph(g, cx + 108 + (j % 2) * 28, cy + 8 + Math.floor(j / 2) * 30, 24);
      });
      const names = e.basic.map((p) => p.shape).join(" + ");
      const shapes = esc(names.length > 30 ? `${names.slice(0, 29)}…` : names);
      body += `<text x="${String(cx + 10)}" y="${String(cy + 84)}" font-size="10" fill="#555">${shapes}</text>`;
      body += `<text x="${String(cx + 10)}" y="${String(cy + 98)}" font-size="10" font-weight="700" fill="${FIT[e.fit]}">${e.fit}</text>`;
    });
    y += Math.ceil(table.glyphs.length / COLS) * CH + 40;
  }
  const w = M * 2 + COLS * CW;
  const legend =
    `<text x="${String(M)}" y="32" font-size="22" font-weight="700">Deq Leet mapping</text>` +
    `<text x="${String(M)}" y="50" font-size="11" fill="#555">Big tile: basic. Small: up to two advanced alternatives, then the full-level motif. Fit: good, fair, rough, or count (digits as dot counts).</text>`;
  return (
    `<!-- Generated by packages/generator/scripts/chart.ts from spec/leet/; do not edit. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" width="${String(w)}" height="${String(y)}" viewBox="0 0 ${String(w)} ${String(y)}" font-family="system-ui, sans-serif" role="img" aria-label="Deq Leet mapping chart">` +
    `<rect width="100%" height="100%" fill="#fafafa"/>${legend}${body}</svg>\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const DIST: string = new URL("../dist/index.js", import.meta.url).href;
  const text = leetChart((await import(DIST)) as typeof Generator);
  if (process.argv.includes("--check")) {
    if (readText(CHART_FILE, 8 * 1024 * 1024) !== text) {
      console.error(
        `${CHART_FILE} is out of date: run \`pnpm --filter @0xdolan/deq-generator fixtures\``,
      );
      process.exit(1);
    }
  } else {
    writeFileSync(CHART_FILE, text);
  }
}
