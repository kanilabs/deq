/**
 * Builds `src/generated/leet.ts` from the Deq Leet tables in `spec/leet/` (ADR 0015). The
 * tables are checked by `uv run deq-spec lint`; this script only copies them.
 *
 *   node scripts/generate-leet.ts           write the file
 *   node scripts/generate-leet.ts --check   fail if the file is out of date
 */
import {
  closeSync,
  constants,
  fstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC_DIR = join(here, "..", "..", "..", "spec", "leet");
export const OUT_FILE = join(here, "..", "src", "generated", "leet.ts");
const SCRIPTS = ["latin", "sorani"] as const;
const MAX_BYTES = 256 * 1024;

/** `O_NOFOLLOW` where the platform has it (not on Windows). */
const NOFOLLOW: number = (constants as Partial<typeof constants>).O_NOFOLLOW ?? 0;

/**
 * Read a regular file of at most `maxBytes` as UTF-8, refusing symlinks. The file is opened
 * once and checked through its descriptor, so it cannot be swapped between check and read.
 */
export function readText(path: string, maxBytes: number = MAX_BYTES): string {
  const fd = openSync(path, constants.O_RDONLY | NOFOLLOW);
  try {
    const st = fstatSync(fd);
    if (!st.isFile()) throw new Error(`${path}: not a regular file`);
    if (st.size > maxBytes) throw new Error(`${path}: larger than ${String(maxBytes)} bytes`);
    return readFileSync(fd, "utf8");
  } finally {
    closeSync(fd);
  }
}

/** The generated module's source text. */
export function generateLeet(specDir: string = SPEC_DIR): string {
  const tables = SCRIPTS.map((script) => {
    const table = JSON.parse(readText(join(specDir, `${script}.json`))) as Record<string, unknown>;
    delete table["$schema"];
    return `  ${script}: ${JSON.stringify(table)},`;
  });
  return [
    "// Generated by scripts/generate-leet.ts from spec/leet/.",
    "// Do not edit: run `pnpm --filter @0xdolan/deq-generator generate`.",
    'import type { LeetTable } from "../tables.js";',
    "",
    "/** The Deq Leet tables, one per script. */",
    "export const TABLES: { readonly latin: LeetTable; readonly sorani: LeetTable } = {",
    ...tables,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generateLeet();
  if (process.argv.includes("--check")) {
    if (readText(OUT_FILE) !== text) {
      console.error(
        `${OUT_FILE} is out of date: run \`pnpm --filter @0xdolan/deq-generator generate\``,
      );
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(OUT_FILE), { recursive: true });
    writeFileSync(OUT_FILE, text);
  }
}
