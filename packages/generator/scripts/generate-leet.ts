/**
 * Builds `src/generated/leet.ts` and the JSON copies read by the Python and Rust ports from
 * the Deq Leet tables in `spec/leet/` (ADR 0015). The tables are checked by
 * `uv run deq-spec lint`; this script only copies them.
 *
 *   node scripts/generate-leet.ts           write the files
 *   node scripts/generate-leet.ts --check   fail if a file is out of date
 */
import {
  closeSync,
  constants,
  fstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC_DIR = join(here, "..", "..", "..", "spec", "leet");
export const OUT_FILE = join(here, "..", "src", "generated", "leet.ts");
const ROOT = join(here, "..", "..", "..");
/** The JSON copies read by the Python and Rust ports. */
export const PORT_FILES = [
  join(ROOT, "python", "deq-shapes", "src", "deq_shapes", "data", "leet.json"),
  join(ROOT, "rust", "deq-shapes", "data", "leet.json"),
];
const SCRIPTS = ["latin", "sorani"] as const;
const MAX_BYTES = 256 * 1024;

/** `O_NOFOLLOW` where the platform has it (not on Windows). */
const NOFOLLOW: number = (constants as Partial<typeof constants>).O_NOFOLLOW ?? 0;

/**
 * Read a regular file of at most `maxBytes` as UTF-8, refusing symlinks. The file is opened
 * once and checked through its descriptor, so it cannot be swapped between check and read.
 */
export function readText(path: string, maxBytes: number = MAX_BYTES): string {
  const fd = openSync(path, constants.O_RDONLY | NOFOLLOW);
  try {
    const st = fstatSync(fd);
    if (!st.isFile()) throw new Error(`${path}: not a regular file`);
    if (st.size > maxBytes) throw new Error(`${path}: larger than ${String(maxBytes)} bytes`);
    return readFileSync(fd, "utf8");
  } finally {
    closeSync(fd);
  }
}

/** Each table as one line of JSON, without its `$schema`. */
function tables(specDir: string): string[] {
  return SCRIPTS.map((script) => {
    const table = JSON.parse(readText(join(specDir, `${script}.json`))) as Record<string, unknown>;
    delete table["$schema"];
    return JSON.stringify(table);
  });
}

/** The generated module's source text. */
export function generateLeet(specDir: string = SPEC_DIR): string {
  const lines = tables(specDir).map((t, i) => `  ${SCRIPTS[i] ?? ""}: ${t},`);
  return [
    "// Generated by scripts/generate-leet.ts from spec/leet/.",
    "// Do not edit: run `pnpm --filter @0xdolan/deq-generator generate`.",
    'import type { LeetTable } from "../tables.js";',
    "",
    "/** The Deq Leet tables, one per script. */",
    "export const TABLES: { readonly latin: LeetTable; readonly sorani: LeetTable } = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

/** The text of the ports' `leet.json`: `{ "$comment", "latin", "sorani" }`. */
export function generatePortData(specDir: string = SPEC_DIR): string {
  const comment = JSON.stringify(
    "Generated by packages/generator/scripts/generate-leet.ts from spec/leet/; do not edit. Run `pnpm --filter @0xdolan/deq-generator generate`.",
  );
  const lines = tables(specDir).map((t, i) => `  "${SCRIPTS[i] ?? ""}": ${t}`);
  return `{\n  "$comment": ${comment},\n${lines.join(",\n")}\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const port = generatePortData();
  const files: [string, string][] = [
    [OUT_FILE, generateLeet()],
    ...PORT_FILES.map((f): [string, string] => [f, port]),
  ];
  for (const [file, text] of files) {
    if (process.argv.includes("--check")) {
      if (readText(file) !== text) {
        console.error(
          `${file} is out of date: run \`pnpm --filter @0xdolan/deq-generator generate\``,
        );
        process.exit(1);
      }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
}
