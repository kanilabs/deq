"""The Deq logo: the Dot rosette from spec/, drawn in the Kanî Labs style (ADR 0013).

Every brand SVG in ``assets/brand/`` is written from the shape's own geometry by
``uv run deq-spec brand``, and ``deq-spec lint`` fails when one is stale.
"""

from __future__ import annotations

import json
import math
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from deq_spec import SpecError, lint, lockups
from deq_spec import geometry as g
from deq_spec.render import num
from deq_spec.spec import ParamValue, expand, read_json

SHAPE = "dot-rosette"
DOTS = 8
PARAMS: dict[str, ParamValue] = {"center": "ring", "dots": DOTS}

# Kanî Labs palette, shared with the other Kanî projects.
GREEN = "#1D4A2E"  # deq ink
SUN = "#FEBD11"  # the sun of the flag
FACE = "#F8F8F8"  # badge disc
INK = "#1E1E1E"  # badge outline and text
GREEN_DARK = "#8FDBA5"  # the site's dark-mode accent (10.85:1 on #17181c)

# Optical weights for 64 px and below, where dots of r 1 and a 2-unit ring disappear.
SMALL_DOT = 1.5
SMALL_RING = 2.4
VIEWBOX = "3 3 18 18"  # the rosette (4 to 20) plus room for the heavier small dots
BADGE_UNIT = 38  # px per grid unit on the 1024 badge
HEADER = (
    "<!-- Generated by `uv run deq-spec brand` from spec/shapes/dot-rosette.json."
    " Do not edit. -->\n"
)


@dataclass(frozen=True)
class Rosette:
    ring: g.Circle
    dots: tuple[g.Circle, ...]
    stroke: float


def rosette(root: Path) -> Rosette:
    """The ring, the dots and the stroke width, from the spec."""
    repo = lint.Repo(root)
    reg = lint.load_registry(repo)
    items = expand(reg.get(SHAPE), reg, PARAMS)
    circles = [i for i in items if isinstance(i, g.Circle)]
    rings = [c for c in circles if not c.dot]
    dots = tuple(c for c in circles if c.dot)
    if len(rings) != 1 or len(dots) != DOTS or len(circles) != len(items):
        raise SpecError(f"{SHAPE}: expected one ring and {DOTS} dots")
    grid = read_json(repo.spec / "grid.json")
    return Rosette(rings[0], dots, float(grid["defaults"]["strokeWidth"]))


def mark(
    r: Rosette,
    *,
    dots: str | Sequence[str],
    ring: str,
    unit: float = 1.0,
    at: tuple[float, float] = (12.0, 12.0),
    small: bool = False,
    dot_class: str = "",
    animated: bool = False,
) -> str:
    """The rosette's elements, with grid (12, 12) at ``at`` and ``unit`` px per grid unit.

    ``dots`` is one fill, or fills repeated clockwise from the top dot. ``animated`` adds the
    classes the animated logo's style sheet times (``dN`` per dot in clockwise order, ``ring``).
    """

    def x(v: float) -> str:
        return num(at[0] + (v - 12) * unit)

    def y(v: float) -> str:
        return num(at[1] + (v - 12) * unit)

    fills = (dots,) if isinstance(dots, str) else tuple(dots)
    cls = f' class="{dot_class}"' if dot_class else ""
    order = r.dots if len(fills) == 1 and not animated else tuple(lockups.clockwise(r.dots))
    out = [f'<g fill="{fills[0]}"{cls}>']
    for i, d in enumerate(order):
        radius = (SMALL_DOT if small else d.r) * unit
        extra = f' fill="{fills[i % len(fills)]}"' if i % len(fills) else ""
        extra += f' class="d{i}"' if animated else ""
        out.append(f'<circle cx="{x(d.cx)}" cy="{y(d.cy)}" r="{num(radius)}"{extra}/>')
    out.append("</g>")
    width = (SMALL_RING if small else r.stroke) * unit
    turn = (
        f' class="ring" transform="rotate(-90 {x(r.ring.cx)} {y(r.ring.cy)})"' if animated else ""
    )
    out.append(
        f'<circle cx="{x(r.ring.cx)}" cy="{y(r.ring.cy)}" r="{num(r.ring.r * unit)}" '
        f'fill="none" stroke="{ring}" stroke-width="{num(width)}"{turn}/>'
    )
    return "".join(out)


def badge(r: Rosette, *, size: float, x: float = 0, y: float = 0, animated: bool = False) -> str:
    """The Kanî badge at ``size`` px: disc, thin outline and the rosette."""
    k = size / 1024
    c = (x + 512 * k, y + 512 * k)
    disc = (
        f'<circle cx="{num(c[0])}" cy="{num(c[1])}" r="{num(490 * k)}" fill="{FACE}" '
        f'stroke="{INK}" stroke-width="{num(4 * k)}"/>'
    )
    return disc + mark(r, dots=GREEN, ring=SUN, unit=BADGE_UNIT * k, at=c, animated=animated)


# The animated logo: dots appear clockwise from the top, then the sun ring draws itself.
DOT_STEP = 0.12  # s between dots
DOT_TIME = 0.32  # s per dot
RING_START = 1.0  # s
RING_TIME = 0.7  # s
ANIMATION = RING_START + RING_TIME


def animation_css(ring_length: float) -> str:
    """The style sheet of the animated logo; still (the finished mark) under reduced motion."""
    dash = num(math.ceil(ring_length) + 1)
    delays = "".join(f"circle.d{i}{{animation-delay:{num(i * DOT_STEP)}s}}" for i in range(DOTS))
    return (
        "<style>"
        f"circle[class^=d]{{animation:deq-dot {num(DOT_TIME)}s cubic-bezier(.2,.8,.2,1) both;"
        "transform-box:fill-box;transform-origin:center}"
        f"{delays}"
        f".ring{{stroke-dasharray:{dash};animation:deq-ring {num(RING_TIME)}s ease-in-out "
        f"{num(RING_START)}s both}}"
        "@keyframes deq-dot{from{opacity:0;transform:scale(.3)}}"
        f"@keyframes deq-ring{{from{{stroke-dashoffset:{dash}}}}}"
        "@media (prefers-reduced-motion:reduce){circle{animation:none!important}}"
        "</style>"
    )


def svg(attrs: str, body: str, title: str = "Deq") -> str:
    return (
        f'{HEADER}<svg xmlns="http://www.w3.org/2000/svg" {attrs}>'
        f"<title>{title}</title>{body}</svg>\n"
    )


def _canvas(width: float, height: float) -> str:
    return f'width="{num(width)}" height="{num(height)}" viewBox="0 0 {num(width)} {num(height)}"'


def title_row(
    t: dict[str, lockups.Text], *, x: float, top: float, cap: float, ink: str, dot: str
) -> tuple[str, float]:
    """``Deq · دەق`` from outlines: Latin cap height ``cap`` with its cap top at ``top``."""
    latin, ckb = t["wordmark"], t["wordmark-ckb"]
    s = cap / latin.cap
    lw, _ = lockups.size(latin, s)
    out = lockups.place(latin, s, x, top, ink)
    center = top + cap / 2
    gap = cap * 0.42
    cx, cy, radius = (num(round(v, 2)) for v in (x + lw + gap, center, cap * 0.09))
    out += f'<circle cx="{cx}" cy="{cy}" r="{radius}" fill="{dot}"/>'
    cs = lockups.CKB / lockups.CAP * cap / (ckb.bbox[3] - ckb.bbox[1])
    cw, ch = lockups.size(ckb, cs)
    out += lockups.place(ckb, cs, x + lw + 2 * gap, center - ch / 2, ink)
    return out, lw + 2 * gap + cw


def line(t: lockups.Text, *, x: float, baseline: float, px: float, fill: str) -> str:
    """One English line at font size ``px`` with its baseline at ``baseline``."""
    s = px / t.upem
    return lockups.place(t, s, x, baseline + t.bbox[1] * s, fill)


def line_width(t: lockups.Text, px: float) -> float:
    return lockups.size(t, px / t.upem)[0]


def social_preview(r: Rosette, t: dict[str, lockups.Text]) -> str:
    """The 1280 x 640 card for the GitHub social preview and social posts."""
    row, _ = title_row(t, x=560, top=214, cap=86, ink=INK, dot=GREEN)
    body = (
        f'<rect width="1280" height="640" fill="{FACE}"/>'
        + badge(r, size=420, x=80, y=110)
        + row
        + line(t["tagline-1"], x=564, baseline=380, px=36, fill=INK)
        + line(t["tagline-2"], x=564, baseline=430, px=36, fill=INK)
        + line(t["url"], x=564, baseline=520, px=28, fill=GREEN)
    )
    return svg(_canvas(1280, 640), body, "Deq · دەق")


def banner(r: Rosette, t: dict[str, lockups.Text], *, dark: bool) -> str:
    """The 1280 x 320 README banner, for light or dark pages."""
    bg, ink, accent = ("#17181C", "#FFFFFF", GREEN_DARK) if dark else (FACE, INK, GREEN)
    row, _ = title_row(t, x=320, top=78, cap=64, ink=ink, dot=accent)
    body = (
        f'<rect width="1280" height="320" fill="{bg}"/>'
        + badge(r, size=240, x=40, y=40)
        + row
        + line(t["tagline-1"], x=322, baseline=218, px=30, fill=ink)
        + line(t["tagline-2"], x=322, baseline=258, px=30, fill=ink)
    )
    return svg(_canvas(1280, 320), body, "Deq · دەق")


def figma_cover(r: Rosette, t: dict[str, lockups.Text], root: Path) -> str:
    """The 1920 x 1080 Figma Community cover (Figma's recommended size)."""
    flag = lockups.flag_colors(root)
    _, width = title_row(t, x=0, top=0, cap=96, ink=INK, dot=GREEN)
    row, _ = title_row(t, x=(1920 - width) / 2, top=600, cap=96, ink=INK, dot=GREEN)
    lines = ""
    for key, baseline in (("tagline-1", 820), ("tagline-2", 876)):
        w = line_width(t[key], 44)
        lines += line(t[key], x=(1920 - w) / 2, baseline=baseline, px=44, fill=INK)
    strip = "".join(
        f'<rect x="{i * 640}" y="1064" width="640" height="16" fill="{flag[c]}"/>'
        for i, c in enumerate(("red", "white", "green"))
    )
    body = (
        f'<rect width="1920" height="1080" fill="{FACE}"/>'
        + badge(r, size=440, x=740, y=100)
        + row
        + lines
        + strip
    )
    return svg(_canvas(1920, 1080), body, "Deq · دەق")


def _drawer(r: Rosette) -> lockups.Drawer:
    def draw(center: tuple[float, float], unit: float, way: lockups.Colorway) -> str:
        return mark(r, dots=way.dots, ring=way.ring, unit=unit, at=center)

    return draw


def lockup_files(r: Rosette, t: dict[str, lockups.Text], root: Path) -> dict[str, str]:
    out = {}
    for way in lockups.colorways(root, GREEN, SUN, INK, GREEN_DARK):
        for stacked in (False, True):
            for ckb in (False, True):
                text = t["wordmark-ckb" if ckb else "wordmark"]
                lk = lockups.lockup(_drawer(r), text, way, stacked=stacked, ckb=ckb)
                w, h = round(lk.width, 2), round(lk.height, 2)
                name = f"{'stacked' if stacked else 'horizontal'}{'-ckb' if ckb else ''}-{way.id}"
                title = "دەق" if ckb else "Deq"
                out[f"assets/brand/lockups/{name}.svg"] = svg(_canvas(w, h), lk.body, title)
        if way.id in ("flag", "white"):
            size = f'width="24" height="24" viewBox="{VIEWBOX}"'
            out[f"assets/brand/mark-{way.id}.svg"] = svg(
                size, mark(r, dots=way.dots, ring=way.ring)
            )
    return out


def construction(r: Rosette) -> str:
    """The mark on its 24-unit grid with the dot circle and the axes (10 px per unit)."""
    grid = "".join(f"M{i * 10} 0V240M0 {i * 10}H240" for i in range(1, 24))
    body = (
        '<rect width="240" height="240" fill="#FFFFFF"/>'
        f'<path d="{grid}" stroke="#D9DCE1" stroke-width="0.5"/>'
        '<path d="M120 0V240M0 120H240" stroke="#9AA0A6" stroke-width="0.75"/>'
        '<circle cx="120" cy="120" r="70" fill="none" stroke="#9AA0A6" stroke-width="0.75" '
        'stroke-dasharray="4 3"/>'
        + mark(r, dots=GREEN, ring=SUN, unit=10, at=(120, 120))
        + '<rect x="40" y="40" width="160" height="160" fill="none" stroke="#ED2024" '
        'stroke-width="0.75" stroke-dasharray="4 3"/>'
    )
    return svg(_canvas(240, 240), body, "Deq mark construction")


def clear_space(r: Rosette, t: dict[str, lockups.Text], root: Path) -> str:
    """The horizontal lockup inside its clear space (a quarter of the mark on every side)."""
    way = lockups.colorways(root, GREEN, SUN, INK, GREEN_DARK)[0]
    c = lockups.CLEAR * lockups.D
    lk = lockups.lockup(_drawer(r), t["wordmark"], way, stacked=False, ckb=False, x=c, y=c)
    w, h = round(lk.width + 2 * c, 2), round(lk.height + 2 * c, 2)
    corners = "".join(
        f'<rect x="{num(x)}" y="{num(y)}" width="{num(c)}" height="{num(c)}" fill="#ED2024" '
        'fill-opacity="0.15"/>'
        for x in (0, w - c)
        for y in (0, h - c)
    )
    body = (
        f'<rect width="{num(w)}" height="{num(h)}" fill="#FFFFFF" stroke="#ED2024" '
        'stroke-dasharray="6 4"/>'
        + corners
        + f'<rect x="{num(c)}" y="{num(c)}" width="{num(round(lk.width, 2))}" '
        f'height="{num(round(lk.height, 2))}" fill="none" stroke="#9AA0A6" stroke-dasharray="4 3"/>'
        + lk.body
    )
    return svg(_canvas(w, h), body, "Deq clear space")


def brand_json(root: Path) -> str:
    flag = lockups.flag_colors(root)
    colors = [
        lockups.color_entry("Deq green", GREEN, "Dots of the mark; brand accent on light"),
        lockups.color_entry("Sun yellow", SUN, "Ring of the mark; the flag's sun"),
        lockups.color_entry("Badge face", FACE, "Disc of the badge; light surfaces"),
        lockups.color_entry("Ink", INK, "Wordmark, badge outline and text on light"),
        lockups.color_entry("Deq green, dark", GREEN_DARK, "Dots and accent on dark"),
        lockups.color_entry("Night", "#17181C", "Dark surfaces"),
        lockups.color_entry("Flag red", flag["red"], "Flag of Kurdistan"),
        lockups.color_entry("Flag white", flag["white"], "Flag of Kurdistan"),
        lockups.color_entry("Flag green", flag["green"], "Flag of Kurdistan"),
        lockups.color_entry("Flag yellow", flag["yellow"], "Flag of Kurdistan (the sun)"),
    ]
    doc = {
        "generated": "uv run deq-spec brand. Do not edit.",
        "proportions": {
            "latinCapHeight": lockups.CAP,
            "soraniHeight": lockups.CKB,
            "gap": lockups.GAP,
            "stackedGap": lockups.STACK_GAP,
            "clearSpace": lockups.CLEAR,
            "note": "Fractions of the mark's diameter.",
        },
        "minSize": {**lockups.MIN_PX, "smallMarkBelow": 64, "unit": "px"},
        "colors": colors,
        "typography": [
            {
                "family": "Noto Sans",
                "use": "Latin wordmark (Bold), UI and English lines",
                "license": "OFL-1.1",
            },
            {"family": "Vazirmatn", "use": "Sorani wordmark (Bold) and UI", "license": "OFL-1.1"},
            {
                "family": "Deq Leet",
                "use": "Deq Leet text",
                "license": "GPL-3.0-or-later WITH Font-exception-2.0",
            },
        ],
        "animation": {"seconds": ANIMATION, "dotStep": DOT_STEP, "ringStart": RING_START},
    }
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def tokens_css(root: Path) -> str:
    data = json.loads(brand_json(root))
    names = [c["name"].lower().replace(",", "").replace(" ", "-") for c in data["colors"]]
    body = "".join(
        f"  --deq-{n}: {c['hex']};\n" for n, c in zip(names, data["colors"], strict=True)
    )
    return f"/* Generated by `uv run deq-spec brand`. Do not edit. */\n:root {{\n{body}}}\n"


def colors_md(root: Path) -> str:
    data = json.loads(brand_json(root))
    rows = [
        "| Colour | HEX | RGB | HSL | OKLCH | CMYK | On white | On night | Use |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for c in data["colors"]:
        h, s, light = c["hsl"]
        lo, ch, hue = c["oklch"]
        rows.append(
            f"| {c['name']} | `{c['hex']}` | {', '.join(map(str, c['rgb']))} | "
            f"{h}°, {s}%, {light}% | {lo} {ch} {hue} | {', '.join(map(str, c['cmyk']))} | "
            f"{c['onWhite']}:1 | {c['onDark']}:1 | {c['use']} |"
        )
    return (
        "<!-- Generated by `uv run deq-spec brand`. Do not edit. -->\n\n"
        "# Brand colours\n\n"
        "CMYK values are a naive conversion for reference, not a press proof. "
        "Pantone values are not given until verified from a primary source.\n\n"
        + "\n".join(rows)
        + "\n"
    )


def files(root: Path) -> dict[str, str]:
    """Every generated brand file, by path relative to the repository root."""
    r = rosette(root)
    t = lockups.texts(root)
    size = f'width="24" height="24" viewBox="{VIEWBOX}"'
    dark = f"<style>@media (prefers-color-scheme: dark){{.d{{fill:{GREEN_DARK}}}}}</style>"
    ring = 2 * math.pi * r.ring.r * BADGE_UNIT
    mark_ring = 2 * math.pi * r.ring.r * lockups.UNIT
    return {
        "assets/brand/logo.svg": svg(
            'width="1024" height="1024" viewBox="0 0 1024 1024"', badge(r, size=1024)
        ),
        "assets/brand/logo-animated.svg": svg(
            'width="1024" height="1024" viewBox="0 0 1024 1024"',
            animation_css(ring) + badge(r, size=1024, animated=True),
        ),
        "assets/brand/mark-animated.svg": svg(
            _canvas(240, 240),
            animation_css(mark_ring)
            + mark(r, dots=GREEN, ring=SUN, unit=lockups.UNIT, at=(120, 120), animated=True),
        ),
        "assets/brand/mark.svg": svg(size, mark(r, dots=GREEN, ring=SUN)),
        "assets/brand/mark-dark.svg": svg(size, mark(r, dots=GREEN_DARK, ring=SUN)),
        "assets/brand/mark-mono.svg": svg(size, mark(r, dots="currentColor", ring="currentColor")),
        "assets/brand/mark-small.svg": svg(size, mark(r, dots=GREEN, ring=SUN, small=True)),
        "assets/brand/mark-small-dark.svg": svg(
            size, mark(r, dots=GREEN_DARK, ring=SUN, small=True)
        ),
        "assets/brand/favicon.svg": svg(
            f'viewBox="{VIEWBOX}"',
            dark + mark(r, dots=GREEN, ring=SUN, small=True, dot_class="d"),
        ),
        "assets/brand/social-preview.svg": social_preview(r, t),
        "assets/brand/banner.svg": banner(r, t, dark=False),
        "assets/brand/banner-dark.svg": banner(r, t, dark=True),
        "assets/brand/figma-cover.svg": figma_cover(r, t, root),
        "assets/brand/guide/construction.svg": construction(r),
        "assets/brand/guide/clear-space.svg": clear_space(r, t, root),
        **lockup_files(r, t, root),
        "assets/brand/brand.json": brand_json(root),
        "assets/brand/tokens.css": tokens_css(root),
        "docs/design/brand-colors.md": colors_md(root),
    }


def stale(root: Path) -> list[str]:
    """Brand files that are missing or differ from what ``files`` would write."""
    out = []
    for rel, text in files(root).items():
        path = root / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out


def write(root: Path) -> list[Path]:
    """Write every brand SVG; returns the paths written."""
    written = []
    for rel, text in files(root).items():
        path = root / rel
        if path.is_symlink():
            raise SpecError(f"{rel}: refusing to write through a symlink")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
