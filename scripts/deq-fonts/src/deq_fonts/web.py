"""Code points, CSS and the code point table."""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path

from deq_fonts.build import COLOR_FAMILY, FAMILY, Shape, ligatures

FIRST = 0xE000
LAST = 0xF8FF


def assign(ids: Sequence[str], current: Mapping[str, str]) -> dict[str, str]:
    """Keep every existing code point (also for removed shapes, so none is reused) and give
    new ids the next free ones in catalog order."""
    out = dict(current)
    used = {int(v, 16) for v in out.values()}
    if len(used) != len(out) or any(not FIRST <= c <= LAST for c in used):
        raise ValueError("code points must be unique and in U+E000-U+F8FF")
    nxt = max(used, default=FIRST - 1) + 1
    for i in ids:
        if i not in out:
            if nxt > LAST:
                raise ValueError("the Private Use Area is full")
            out[i] = f"{nxt:04X}"
            nxt += 1
    return out


def load_codepoints(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {str(k): str(v) for k, v in data["codepoints"].items()}


def codepoints_json(codepoints: Mapping[str, str]) -> str:
    body = {
        "description": "Private Use Area code points of the Deq icon fonts. Generated by "
        "`uv run deq-fonts codepoints`; never change or reuse a value.",
        "codepoints": dict(codepoints),
    }
    return json.dumps(body, indent=2, ensure_ascii=False) + "\n"


def css(shapes: Sequence[Shape], codepoints: Mapping[str, str]) -> str:
    """``deq-icons.css``: the font faces, the ``.deq`` class and one class per icon."""
    rules = [
        "/* Deq icon fonts. Generated by `uv run deq-fonts build`; do not edit. */",
        "@font-face {",
        f'  font-family: "{FAMILY}";',
        '  src: url("DeqIcons[DOTS,wght].woff2") format("woff2") tech(variations),',
        '    url("DeqIcons[DOTS,wght].woff2") format("woff2-variations"),',
        '    url("DeqIcons-Regular.woff2") format("woff2");',
        "  font-weight: 100 900;",
        "  font-style: normal;",
        "  font-display: block;",
        "}",
        "@font-face {",
        f'  font-family: "{COLOR_FAMILY}";',
        '  src: url("DeqIconsColor-Regular.woff2") format("woff2");',
        "  font-weight: 400;",
        "  font-style: normal;",
        "  font-display: block;",
        "}",
        ".deq,",
        ".deq-color {",
        f'  font-family: "{FAMILY}";',
        "  font-style: normal;",
        "  font-weight: 400;",
        "  line-height: 1;",
        "  display: inline-block;",
        "  text-transform: none;",
        "  white-space: nowrap;",
        '  font-feature-settings: "liga";',
        "  -webkit-font-smoothing: antialiased;",
        "}",
        f'.deq-color {{\n  font-family: "{COLOR_FAMILY}";\n}}',
    ]
    for s in shapes:
        rules.append(f'.deq-{s.id}::before {{\n  content: "\\{codepoints[s.id].lower()}";\n}}')
    return "\n".join(rules) + "\n"


def table(shapes: Sequence[Shape], codepoints: Mapping[str, str]) -> str:
    """The Markdown code point table for ``docs/fonts.md``."""
    ligs: dict[str, list[str]] = {}
    for text, glyph in ligatures(shapes).items():
        ligs.setdefault(glyph, []).append(text)
    rows = [
        "<!-- Generated by `uv run deq-fonts codepoints`; do not edit. -->",
        "",
        "| Code point | Icon | CSS class | Ligatures |",
        "| ---------- | ---- | --------- | --------- |",
    ]
    for s in shapes:
        names = ", ".join(f"`{t}`" for t in ligs.get(s.glyph_name, []))
        rows.append(f"| U+{codepoints[s.id]} | {s.name} | `.deq-{s.id}` | {names} |")
    return "\n".join(rows) + "\n"
